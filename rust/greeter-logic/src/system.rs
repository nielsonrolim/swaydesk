//! O que a tela de login tira do sistema, porque o greetd não passa: o idioma (o LANG do
//! /etc/locale.conf ou do /etc/default/locale), a config própria (/etc/swaydesk-greeter/config.toml, no
//! formato da config.toml de cada usuário: `accent` e `locale`) e o comando que aplica o teclado.
use std::path::Path;

use swaydesk_common::config::{self, Config};

pub const CONFIG_FILE: &str = "/etc/swaydesk-greeter/config.toml";
/// Os arquivos do idioma do sistema, na ordem: o do systemd (Arch, Fedora), depois o do Debian.
pub const LOCALE_FILES: [&str; 2] = ["/etc/locale.conf", "/etc/default/locale"];

/// O LANG do primeiro arquivo que o tiver, sem aspas. Vazio sem nenhum.
pub fn system_lang(files: &[&Path]) -> String {
    for file in files {
        let Ok(text) = std::fs::read_to_string(file) else { continue };
        for line in text.lines() {
            if let Some(value) = line.trim().strip_prefix("LANG=") {
                let value = value.trim().trim_matches('"').trim_matches('\'');
                if !value.is_empty() {
                    return value.to_string();
                }
            }
        }
    }
    String::new()
}

/// A config da tela: a do arquivo (avisos no stderr) e, sem `locale` nela, o idioma do sistema.
pub fn greeter_config(file: &Path, lang: &str) -> Config {
    let (mut config, warnings) = config::load_config(file);
    for warning in warnings {
        eprintln!("{warning}");
    }
    if config.locale.is_empty() {
        let env = std::collections::HashMap::from([("LANG".to_string(), lang.to_string())]);
        config.locale = config::effective_locale(&config, &env);
    }
    config
}

/// O comando do swaymsg com o teclado do sistema, ou None se não há o que mudar. Os valores vão entre
/// aspas: pelo IPC, o Sway separa os comandos na vírgula, e "br,us" viraria dois comandos. O
/// `xkb_settings` só deixa passar `[A-Za-z0-9_,:()+-]`, então as aspas não têm como ser fechadas antes.
pub fn keyboard_command(settings: &[(&str, String)]) -> Option<String> {
    if settings.is_empty() {
        return None;
    }
    let parts: Vec<String> = settings.iter().map(|(key, value)| format!("xkb_{key} \"{value}\"")).collect();
    // Um comando por opção, separados por ';': o "input" do Sway aceita uma opção de cada vez
    Some(parts.iter().map(|p| format!("input type:keyboard {p}")).collect::<Vec<_>>().join("; "))
}

#[cfg(test)]
mod tests {
    use super::*;
    use swaydesk_common::keyboard::xkb_settings;

    #[test]
    fn the_system_language() {
        let dir = std::env::temp_dir().join(format!("swaydesk-greeter-system-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let (systemd, debian) = (dir.join("locale.conf"), dir.join("locale"));
        assert_eq!(system_lang(&[&systemd, &debian]), "");
        std::fs::write(&debian, "#  File generated by update-locale\nLANG=\"pt_BR.UTF-8\"\n").unwrap();
        assert_eq!(system_lang(&[&systemd, &debian]), "pt_BR.UTF-8");
        std::fs::write(&systemd, "LC_TIME=en_GB.UTF-8\nLANG=en_US.UTF-8\n").unwrap();
        assert_eq!(system_lang(&[&systemd, &debian]), "en_US.UTF-8");
        assert_eq!(greeter_config(&dir.join("config.toml"), "pt_BR.UTF-8").locale, "pt_BR");
        assert_eq!(greeter_config(&dir.join("config.toml"), "C.UTF-8").locale, "");
        std::fs::write(dir.join("config.toml"), "accent = \"#8e44ad\"\nlocale = \"en_US\"\n").unwrap();
        let config = greeter_config(&dir.join("config.toml"), "pt_BR.UTF-8");
        assert_eq!((config.accent.as_str(), config.locale.as_str()), ("#8e44ad", "en_US"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn keyboard_values_with_commas_are_quoted() {
        let settings = xkb_settings("XKBMODEL=\"abnt2\"\nXKBLAYOUT=\"br,us\"\nXKBVARIANT=\"abnt2,intl\"\nXKBOPTIONS=\"grp:alt_shift_toggle,ctrl:nocaps\"\n");
        assert_eq!(
            keyboard_command(&settings).unwrap(),
            "input type:keyboard xkb_model \"abnt2\"; input type:keyboard xkb_layout \"br,us\"; \
             input type:keyboard xkb_variant \"abnt2,intl\"; input type:keyboard xkb_options \"grp:alt_shift_toggle,ctrl:nocaps\""
        );
        assert_eq!(keyboard_command(&xkb_settings("XKBLAYOUT=\"us\"\n")), None);
    }
}
